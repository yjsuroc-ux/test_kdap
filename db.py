# PostgreSQL: 자동 증가 키만 다르다.
PG_SCHEMA = SCHEMA.replace("id INTEGER PRIMARY KEY", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")

SEED_TEMPLATES = [
    ("심의위원회형", [("소요 검토", 7), ("심의위원회 개최", 4), ("결과 회신", 0)]),
    ("단순 회신형", [("검토 및 자료 작성", 3), ("회신", 0)]),
    ("전파형", [("관련부서 전파", 0)]),
]


def now():
    return dt.datetime.now(KST).strftime("%Y-%m-%d %H:%M:%S")


def today():
    return dt.datetime.now(KST).date()


BACKUP_DIR = os.environ.get("DEADLINE_BACKUP_DIR", os.path.join(BASE, "backup"))
CAN_BACKUP = BACKEND == "sqlite"  # 클라우드 DB는 파일 백업 대신 DB 서비스의 백업 기능을 쓴다


def backup(prefix="tasks"):
    """DB를 backup/ 폴더에 복사한다(서버 실행 중에도 안전). 기존 백업은 덮어쓰지 않는다.
    → 백업 파일 경로. 파일 백업을 할 수 없는 환경이면 None."""
    if not CAN_BACKUP:
        return None
    os.makedirs(BACKUP_DIR, exist_ok=True)
    stem = os.path.join(BACKUP_DIR, f"{prefix}_{dt.datetime.now(KST):%Y%m%d_%H%M%S}")
    dest, n = stem + ".db", 1
    while os.path.exists(dest):
        n += 1
        dest = f"{stem}_{n}.db"
    src, dst = sqlite3.connect(DB_PATH), sqlite3.connect(dest)
    try:
        src.backup(dst)
    finally:
        dst.close()
        src.close()
    return dest


# ================================================================ PostgreSQL 어댑터

class _Row(dict):
    """sqlite3.Row처럼 이름(r["id"])과 순번(r[0]) 둘 다로 읽을 수 있는 행."""

    def __init__(self, cols, values):
        super().__init__(zip(cols, values))
        self._values = values

    def __getitem__(self, k):
        return self._values[k] if isinstance(k, int) else super().__getitem__(k)


class _PgCursor:
    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid, self.rowcount = cur, lastrowid, cur.rowcount

    def _row(self, values):
        return None if values is None else _Row([d.name for d in self._cur.description], values)

    def fetchone(self):
        return self._row(self._cur.fetchone()) if self._cur.description else None

    def fetchall(self):
        return [self._row(v) for v in self._cur.fetchall()] if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


_INSERT_ID = re.compile(r"^\s*INSERT\s+INTO\s+(staff|task|step|template|template_step)\b", re.I)
_UPSERT = re.compile(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)\s*\(([^)]*)\)", re.I)
_UPSERT_KEYS = {"settings": "key", "import_session": "id"}


class _PgConn:
    def __init__(self, url):
        import psycopg

        # prepare_threshold=None: 서버 측 prepared statement를 쓰지 않는다.
        # Supabase 트랜잭션 풀러(6543)·PgBouncer는 이를 지원하지 않아, 같은 쿼리를 여러 번 돌리면 오류가 난다.
        self._c = psycopg.connect(url, connect_timeout=10, prepare_threshold=None)

    def execute(self, sql, params=()):
        m = _UPSERT.match(sql)
        if m:  # INSERT OR REPLACE → ON CONFLICT DO UPDATE
            table, cols = m.group(1), [c.strip() for c in m.group(2).split(",")]
            key = _UPSERT_KEYS[table]
            sets = ", ".join(f"{c}=EXCLUDED.{c}" for c in cols if c != key)
            sql = _UPSERT.sub(f"INSERT INTO {table}({', '.join(cols)})", sql) + f" ON CONFLICT ({key}) DO UPDATE SET {sets}"
        returning = bool(_INSERT_ID.match(sql)) and "RETURNING" not in sql.upper()
        if returning:
            sql += " RETURNING id"
        cur = self._c.cursor()
        cur.execute(sql.replace("?", "%s"), tuple(params))
        lastrowid = cur.fetchone()[0] if returning else None
        return _PgCursor(cur, lastrowid)

    def commit(self):
        self._c.commit()

    def close(self):
        self._c.close()


# ================================================================ 연결·초기화

def connect():
    if BACKEND == "postgres":
        return _PgConn(PG_URL)
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _seed(conn):
    for name, steps in SEED_TEMPLATES:
        tid = conn.execute("INSERT INTO template(name) VALUES (?)", (name,)).lastrowid
        for i, (sname, days) in enumerate(steps):
            conn.execute(
                "INSERT INTO template_step(template_id, ord, name, days_before) VALUES (?,?,?,?)",
                (tid, i, sname, days),
            )


def init():
    if BACKEND == "postgres":
        return _init_pg()
    os.makedirs(DATA_DIR, exist_ok=True)
    conn = connect()
    try:
        conn.execute("PRAGMA journal_mode = WAL")
        conn.executescript(SCHEMA)
        # 이전 버전 DB 갱신: 접수번호·생산일자 열 추가. 문서번호는 기관이 달라 겹칠 수 있어 고유 제약을 없앤다.
        cols = {r["name"] for r in conn.execute("PRAGMA table_info(task)")}
        for col in ("receipt_no", "receipt_no_norm", "produced_date"):
            if col not in cols:
                conn.execute(f"ALTER TABLE task ADD COLUMN {col} TEXT")
        conn.execute("DROP INDEX IF EXISTS ux_task_docno")
        conn.execute("CREATE INDEX IF NOT EXISTS ix_task_docno ON task(doc_no_norm)")
        conn.execute("CREATE INDEX IF NOT EXISTS ix_task_receipt ON task(receipt_no_norm)")
        if conn.execute("SELECT COUNT(*) FROM template").fetchone()[0] == 0 and \
                conn.execute("SELECT value FROM settings WHERE key='seeded'").fetchone() is None:
            _seed(conn)
            conn.execute("INSERT OR REPLACE INTO settings(key, value) VALUES ('seeded', '1')")
        conn.commit()
    finally:
        conn.close()


def _init_pg():
    conn = connect()
    try:
        for stmt in PG_SCHEMA.split(";"):
            stmt = re.sub(r"--[^\n]*", "", stmt).strip()
            if stmt:
                conn.execute(stmt)
        conn.execute("CREATE INDEX IF NOT EXISTS ix_task_docno ON task(doc_no_norm)")
        conn.execute("CREATE INDEX IF NOT EXISTS ix_task_receipt ON task(receipt_no_norm)")
        # 행 수준 보안(RLS) 켜기: Supabase는 표를 자동 REST API로도 내보내는데, RLS를 켜고 정책을 두지 않으면
        # 그 API로는 읽기·쓰기가 막힌다. 이 앱은 표 소유자로 접속하므로 영향이 없다. 다른 PostgreSQL에서도 무해하다.
        for table in ("staff", "task", "step", "template", "template_step", "settings", "import_session"):
            conn.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # 여러 서버가 동시에 처음 뜰 때 기본 템플릿이 두 번 들어가지 않도록, 'seeded' 표시를 먼저 차지한 쪽만 넣는다.
        first = conn.execute(
            "INSERT INTO settings(key, value) VALUES ('seeded', '1') ON CONFLICT (key) DO NOTHING RETURNING key"
        ).fetchone()
        if first:
            _seed(conn)
        conn.commit()
    finally:
        conn.close()
