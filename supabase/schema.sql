-- 문서 처리 기한 관리 도구: Supabase(PostgreSQL) 표 정의
-- 이 파일은 tools/make_schema_sql.py가 db.py에서 만든다. 직접 고치지 말 것.
-- 앱이 첫 요청 때 같은 표를 자동으로 만들므로, 미리 만들거나 구조를 확인할 때만 SQL Editor에서 실행한다.

CREATE TABLE IF NOT EXISTS staff (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS task (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,                 -- 가져오기 / 직접
    doc_no TEXT,                          -- 발신 문서번호(시행번호)
    doc_no_norm TEXT,
    receipt_no TEXT,                      -- 우리 부서 접수번호
    receipt_no_norm TEXT,
    title TEXT NOT NULL,
    sender TEXT,
    produced_date TEXT,                   -- 생산일자(발신부서가 생산한 날)
    received_date TEXT,
    assignee_id INTEGER NOT NULL REFERENCES staff(id),
    type TEXT NOT NULL,                   -- 회신 / 전파
    deadline TEXT,
    type_source TEXT NOT NULL DEFAULT 'manual',      -- auto / manual
    deadline_source TEXT NOT NULL DEFAULT 'manual',  -- auto / manual
    evidence TEXT,                        -- JSON
    status TEXT NOT NULL DEFAULT '진행중', -- 진행중 / 완료
    completed_at TEXT,
    memo TEXT,
    body_text TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    updated_by TEXT
);

CREATE TABLE IF NOT EXISTS step (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id INTEGER NOT NULL REFERENCES task(id) ON DELETE CASCADE,
    ord INTEGER NOT NULL,
    name TEXT NOT NULL,
    deadline TEXT,
    done INTEGER NOT NULL DEFAULT 0,
    done_at TEXT
);

CREATE INDEX IF NOT EXISTS ix_step_task ON step(task_id);

CREATE TABLE IF NOT EXISTS template (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS template_step (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id INTEGER NOT NULL REFERENCES template(id) ON DELETE CASCADE,
    ord INTEGER NOT NULL,
    name TEXT NOT NULL,
    days_before INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS import_session (  -- 가져오기 미리보기 상태(업로드→미리보기→등록 사이)
    id TEXT PRIMARY KEY,
    created REAL NOT NULL,
    data TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_task_docno ON task(doc_no_norm);
CREATE INDEX IF NOT EXISTS ix_task_receipt ON task(receipt_no_norm);

-- 행 수준 보안(RLS): Supabase 자동 REST API(anon 키)로는 읽기·쓰기를 막는다.
-- 앱은 표 소유자(postgres)로 접속하므로 영향을 받지 않는다.
ALTER TABLE staff ENABLE ROW LEVEL SECURITY;
ALTER TABLE task ENABLE ROW LEVEL SECURITY;
ALTER TABLE step ENABLE ROW LEVEL SECURITY;
ALTER TABLE template ENABLE ROW LEVEL SECURITY;
ALTER TABLE template_step ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE import_session ENABLE ROW LEVEL SECURITY;

